"""Generate the GitHub Wiki pages in ``wiki/`` from the Marp slides.

Each ``sessions/NN-name/slides.md`` becomes one wiki page. ``Home.md`` and
``_Sidebar.md`` are built from the module structure in ``CURRICULUM.md``.

Usage (from the repo root):
    python tools/build_wiki.py            # regenerate wiki/
    python tools/build_wiki.py --check    # exit 1 if wiki/ is out of date

Don't edit files in ``wiki/`` by hand: they are overwritten on every build.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SESSIONS_DIR = ROOT / "sessions"
WIKI_DIR = ROOT / "wiki"
CURRICULUM = ROOT / "CURRICULUM.md"
DEFAULT_REPO = "tibormezzei/de-pathway-learning"
BRANCH = "main"

# Folders inside a session that get a link in the page footer, in display order.
MATERIALS = {
    "exercise": "Exercise",
    "homework": "Homework",
    "demo": "Demo",
    "data": "Data",
    "solutions": "Solutions",
}

MODULE_ICONS = ["🧭", "🏗️", "✅", "📐", "🤝"]

GENERATED_NOTE = (
    "<!-- Generated by tools/build_wiki.py from the session slides. "
    "Do not edit: changes will be overwritten. -->\n"
)

# How words from session folder names are written in wiki page names.
SPECIAL_WORDS = {"sql": "SQL", "tdd": "TDD", "pyspark": "PySpark"}
SMALL_WORDS = {"and", "is", "to", "for", "of"}


@dataclass
class Session:
    number: int
    title: str
    folder: Path | None = None

    @property
    def page(self) -> str:
        """Wiki page name (file name without .md, also the link target)."""
        slug = re.sub(r"^\d+-", "", self.folder.name)
        words = "-".join(
            SPECIAL_WORDS.get(w) or (w if i and w in SMALL_WORDS else w.capitalize())
            for i, w in enumerate(slug.split("-"))
        )
        return f"Session-{self.number:02d}-{words}"

    @property
    def label(self) -> str:
        return f"{self.number:02d}. {self.title}"


@dataclass
class Module:
    number: int
    title: str
    sessions: list[Session] = field(default_factory=list)


def repo_slug() -> str:
    """owner/name of the GitHub repo, used for links to files in the repo."""
    if os.environ.get("GITHUB_REPOSITORY"):
        return os.environ["GITHUB_REPOSITORY"]
    try:
        url = subprocess.run(
            ["git", "remote", "get-url", "origin"],
            cwd=ROOT, capture_output=True, text=True, check=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return DEFAULT_REPO
    match = re.search(r"github\.com[:/](.+?)(?:\.git)?$", url)
    return match.group(1) if match else DEFAULT_REPO


def parse_curriculum() -> list[Module]:
    modules: list[Module] = []
    for line in CURRICULUM.read_text(encoding="utf-8").splitlines():
        if m := re.match(r"^## Module (\d+):\s*(.+)$", line):
            modules.append(Module(int(m.group(1)), m.group(2).strip()))
        elif (m := re.match(r"^### (\d+)\.\s*(.+)$", line)) and modules:
            modules[-1].sessions.append(Session(int(m.group(1)), m.group(2).strip()))

    folders = {int(p.name[:2]): p for p in SESSIONS_DIR.glob("[0-9][0-9]-*") if p.is_dir()}
    for module in modules:
        for session in module.sessions:
            if session.number not in folders:
                sys.exit(f"CURRICULUM.md lists session {session.number}, but there is no sessions/{session.number:02d}-* folder")
            session.folder = folders[session.number]
    return modules


def split_slides(text: str) -> list[str]:
    """Strip the Marp front matter and split on ``---`` slide breaks outside code fences."""
    lines = text.splitlines()
    if lines and lines[0].strip() == "---":
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
        lines = lines[end + 1:]

    slides, current, in_fence = [], [], False
    for line in lines:
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        if line.strip() == "---" and not in_fence:
            slides.append("\n".join(current))
            current = []
        else:
            current.append(line)
    slides.append("\n".join(current))
    return [s.strip() for s in slides if s.strip()]


def clean_slide(slide: str) -> str:
    """Drop HTML comments (Marp directives and speaker notes) outside code fences.

    The wiki shows what learners see on screen; speaker notes are presenter cues.
    """
    out, in_fence, in_comment = [], False, False
    for line in slide.splitlines():
        if in_comment:
            in_comment = "-->" not in line
            continue
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        if not in_fence and line.lstrip().startswith("<!--"):
            in_comment = "-->" not in line
            continue
        out.append(line)
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()


def tree_url(repo: str, path: Path) -> str:
    rel = path.relative_to(ROOT).as_posix()
    return f"https://github.com/{repo}/tree/{BRANCH}/{rel}"


def blob_url(repo: str, path: Path) -> str:
    rel = path.relative_to(ROOT).as_posix()
    return f"https://github.com/{repo}/blob/{BRANCH}/{rel}"


def nav_line(prev: Session | None, nxt: Session | None) -> str:
    parts = []
    if prev:
        parts.append(f"⬅️ [{prev.label}]({prev.page})")
    parts.append("🏠 [Home](Home)")
    if nxt:
        parts.append(f"[{nxt.label}]({nxt.page}) ➡️")
    return " · ".join(parts)


def session_page(session: Session, module: Module, prev: Session | None,
                 nxt: Session | None, repo: str) -> str:
    slides_path = session.folder / "slides.md"
    slides = split_slides(slides_path.read_text(encoding="utf-8"))
    # The first slide is the Marp title slide; the page header replaces it.
    body = [clean_slide(s) for s in slides[1:]]

    materials = [
        f"- [{label}]({tree_url(repo, session.folder / name)})"
        for name, label in MATERIALS.items()
        if (session.folder / name).is_dir()
    ]
    materials.append(f"- [Slides source (Marp)]({blob_url(repo, slides_path)})")

    parts = [
        GENERATED_NOTE,
        f"# Session {session.number:02d}: {session.title}",
        "",
        f"**Module {module.number}: {module.title}**",
        "",
        nav_line(prev, nxt),
        "",
        "---",
        "",
        "\n\n".join(body),
        "",
        "---",
        "",
        "## 📂 Session materials",
        "",
        *materials,
        "",
        nav_line(prev, nxt),
        "",
    ]
    return "\n".join(parts)


def home_page(modules: list[Module], repo: str) -> str:
    lines = [
        GENERATED_NOTE,
        "# Data Engineering Learning Sessions",
        "",
        "Weekly 60-minute sessions covering the core data engineering skills from the "
        "ONS Data Engineering Learning Pathway, written for Data Engineers at HEO grade. "
        "Each session is a concept presentation followed by either an in-session exercise "
        "or homework, and ends with a **CDP today → GCP tomorrow** bridge.",
        "",
        "Each page below is the slide content for one session. Exercises, data and "
        f"solutions live in the [repository](https://github.com/{repo}).",
        "",
    ]
    for module, icon in zip(modules, MODULE_ICONS * 2):
        lines += [f"## {icon} Module {module.number}: {module.title}", ""]
        lines += [f"- [{s.label}]({s.page})" for s in module.sessions]
        lines.append("")
    lines += [
        "## 🎓 Capstone",
        "",
        f"An optional end-of-series project: [brief, rubric and data]({tree_url(repo, ROOT / 'capstone')}).",
        "",
        "## 💻 Local setup",
        "",
        f"See the [repository README]({blob_url(repo, ROOT / 'README.md')}#local-setup) "
        "for Python, Java and PySpark setup, including Windows gotchas.",
        "",
    ]
    return "\n".join(lines)


def sidebar(modules: list[Module], repo: str) -> str:
    lines = [
        GENERATED_NOTE,
        "## 📖 DE Learning Sessions",
        "",
        "🏠 **[Home](Home)**",
        "",
    ]
    for module, icon in zip(modules, MODULE_ICONS * 2):
        lines += ["---", "", f"### {icon} Module {module.number}", f"**{module.title}**", ""]
        lines += [f"- [{s.label}]({s.page})" for s in module.sessions]
        lines.append("")
    lines += ["---", "", f"🎓 [Capstone]({tree_url(repo, ROOT / 'capstone')})", ""]
    return "\n".join(lines)


def build() -> dict[str, str]:
    repo = repo_slug()
    modules = parse_curriculum()
    ordered = [(s, m) for m in modules for s in m.sessions]

    pages = {"Home.md": home_page(modules, repo), "_Sidebar.md": sidebar(modules, repo)}
    for i, (session, module) in enumerate(ordered):
        prev = ordered[i - 1][0] if i > 0 else None
        nxt = ordered[i + 1][0] if i + 1 < len(ordered) else None
        pages[f"{session.page}.md"] = session_page(session, module, prev, nxt, repo)
    return pages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="don't write; exit 1 if wiki/ differs from a fresh build")
    args = parser.parse_args()

    pages = build()
    existing = {p.name for p in WIKI_DIR.glob("*.md")} if WIKI_DIR.exists() else set()

    if args.check:
        stale = sorted(
            name for name, text in pages.items()
            if not (WIKI_DIR / name).exists()
            or (WIKI_DIR / name).read_text(encoding="utf-8") != text
        ) + sorted(existing - pages.keys())
        if stale:
            print("wiki/ is out of date. Run: python tools/build_wiki.py")
            for name in stale:
                print(f"  {name}")
            return 1
        print(f"wiki/ is up to date ({len(pages)} pages).")
        return 0

    WIKI_DIR.mkdir(exist_ok=True)
    for name in existing - pages.keys():
        (WIKI_DIR / name).unlink()
    for name, text in pages.items():
        (WIKI_DIR / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {len(pages)} pages to {WIKI_DIR.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
